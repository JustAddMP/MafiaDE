#!/usr/bin/env python3
"""Extract the guest-world replay data (tests/data/guest_world_1020.h) from the 2026-10-20 two-PC guest traces.

Usage: python tools/extract_guest_world.py <guest trace A> <guest trace B> > tests/data/guest_world_1020.h

Per guest session, one row per PDL record (1 Hz, ped_sync.lua): seconds since the trace began, whether the guest was
in the world (from the log line `sync: local player in world` to the END record), his own ambient humans (PDL amb),
the state of ped_sync's copy spawner (PDL fac: 0 none, 1 obtain, 2 spawn, 3 ready) and his own traffic cars within
70 m (the nearest TRL mine). Plus the moments of the session: the first tick in the world, 0.16's own switch-off
(`another player's traffic runs here`), the first BlockSpawnersInSphere, and the end. Standard library only.
"""
import re
import sys

FAC = {"none": 0, "obtain": 1, "spawn": 2, "ready": 3}


def fields(rest):
    out = {}
    for tok in rest.split():
        if "=" in tok:
            k, v = tok.split("=", 1)
            out[k] = v
    return out


def extract(path):
    t0 = None
    inworld = None
    off016 = None
    block = None
    end = None
    pdl, trl = [], []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            parts = line.rstrip("\n").split(" ", 2)
            if len(parts) < 2:
                continue
            try:
                t = float(parts[0])
            except ValueError:
                continue
            if t0 is None:
                t0 = t
            kind, rest = parts[1], parts[2] if len(parts) > 2 else ""
            if kind == "PDL":
                pdl.append((t, fields(rest)))
            elif kind == "TRL":
                trl.append((t, fields(rest)))
            elif kind == "END":
                end = t
            elif re.match(r"^\d{4}-\d\d-\d\d$", kind):
                if inworld is None and "sync: local player in world" in rest:
                    inworld = t
                elif off016 is None and "another player's traffic runs here" in rest:
                    off016 = t
                elif block is None and "our pedestrian spawners blocked around us" in rest:
                    block = t
    rows = []
    j = 0
    for t, f in pdl:
        while j + 1 < len(trl) and abs(trl[j + 1][0] - t) <= abs(trl[j][0] - t):
            j += 1
        mine = int(trl[j][1].get("mine", "0")) if trl and abs(trl[j][0] - t) <= 1.0 else 0
        w = 1 if inworld is not None and t >= inworld and (end is None or t <= end) else 0
        rows.append((t - t0, w, int(f.get("amb", "0")), FAC.get(f.get("fac", "none"), 0), mine))
    rel = lambda x: -1.0 if x is None else x - t0
    return rel(inworld), rel(off016), rel(block), rel(end), rows


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    out = []
    out.append("#pragma once")
    out.append("// Generated by tools/extract_guest_world.py from the 2026-10-20 two-PC guest traces (session A: Miles")
    out.append("// mafiacoop-20261020-024103.trace, session B: Adam mafiacoop-20261020-024844.trace). Do not edit by hand.")
    out.append("// Per row: s since the trace began, in the world, own ambient humans (PDL amb), ped_sync's copy spawner")
    out.append("// (0 none 1 obtain 2 spawn 3 ready), own traffic cars within 70 m (TRL mine).")
    out.append("namespace gw1020 {")
    out.append("struct Row { float t; int inWorld, amb, fac, mine; };")
    out.append("struct Session { const char* name; float inWorld, off016, block016, end; const Row* rows; int n; };")
    names = ("A", "B")
    for name, path in zip(names, sys.argv[1:]):
        inworld, off016, block, end, rows = extract(path)
        out.append("constexpr Row k%s[] = {" % name)
        for r in rows:
            out.append("    {%.2ff, %d, %d, %d, %d}," % r)
        out.append("};")
        out.append("constexpr float k%sInWorld = %.2ff, k%sOff016 = %.2ff, k%sBlock016 = %.2ff, k%sEnd = %.2ff;" % (
            name, inworld, name, off016, name, block, name, end))
    out.append("constexpr Session kSessions[] = {")
    for name in names:
        out.append("    {\"%s\", k%sInWorld, k%sOff016, k%sBlock016, k%sEnd, k%s, static_cast<int>(sizeof k%s / sizeof k%s[0])}," % (
            name, name, name, name, name, name, name, name))
    out.append("};")
    out.append("}  // namespace gw1020")
    sys.stdout.buffer.write(("\r\n".join(out) + "\r\n").encode("ascii"))  # CRLF, as the repo checks it out
    return 0


if __name__ == "__main__":
    sys.exit(main())
