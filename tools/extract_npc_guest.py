#!/usr/bin/env python3
"""Extract a guest's own NPCs with a job from a sync trace into tests/data/npc_guest_1020.h (tests/npc_hold_test.cpp).

Usage: extract_npc_guest.py <guest trace> [out.h]

Reads the 0.16 guest trace records (docs/sync-trace.md):
  NGO  key owned=1/0       the C++ GuestOwner made our NPC our own (unpaired 5 s, alive, with a job) / ended it
  NGE  key why=...         the GuestNpcEnd that went with it (0 died, 1 handed back, 2 gone, 3 refused)
  NO   key p hp dead ai    our own NPC, 2 Hz while it was ours
  NP   key loc copy ai ... a host NPC and the local NPC paired with it (copy=0: our own NPC, not a spawned copy), 2 Hz
  NPT  key ...             a state of our own NPC sent to the host (counted: what the old rule sent)
and the NetMonitor lines of the guest-owned messages (GuestNpcStates2 / GuestNpcInfo / ... out KB/s) for the bytes.
Times are seconds from the trace's first record."""
import re
import sys
from collections import defaultdict

FIELD = re.compile(r"(\w+)=(\S+)")
MSG = re.compile(r"(GuestNpc\w+|HostNpcHit|NpcClaim|0x042[0-6]) out ([\d.]+) KB/s ([\d.]+)/s")


def main():
    path = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else None
    t0 = None
    t_end = 0.0
    ngo, nge, no, paired, npt = [], [], [], [], 0
    reports = []  # (t, KB/s out, msgs/s out) of the guest-owned messages, per NetMonitor report
    with open(path, "rb") as f:
        for raw in f:
            line = raw.decode("utf-8", "replace").rstrip("\r\n")
            parts = line.split(" ", 2)
            if len(parts) < 2:
                continue
            try:
                t = float(parts[0])
            except ValueError:
                continue
            if t0 is None:
                t0 = t
            t_end = t
            kind, rest = parts[1], parts[2] if len(parts) > 2 else ""
            if "net: messages: " in line:
                kbs = msgs = 0.0
                for m in MSG.finditer(line):
                    kbs += float(m.group(2))
                    msgs += float(m.group(3))
                reports.append((t - t0, kbs, msgs))
                continue
            fl = dict(FIELD.findall(rest))
            if kind == "NGO":
                ngo.append((t - t0, int(fl["key"]), int(fl["owned"])))
            elif kind == "NGE" and "from" not in fl:
                nge.append((t - t0, int(fl["key"]), int(fl["why"])))
            elif kind == "NO":
                x, y, z = (float(v) for v in fl["p"].split(","))
                no.append((t - t0, int(fl["key"]), x, y, z, int(fl["ai"]), int(float(fl["hp"])), int(fl["dead"])))
            elif kind == "NP" and fl.get("copy") == "0" and fl.get("loc", "nil").isdigit() and fl.get("ai") != "0":
                # one of our NPCs (not a spawned copy) with a job, paired with a host NPC
                our = fl.get("our", "-")
                x, y, z = (float(v) for v in our.split(",")) if our != "-" else (0.0, 0.0, 0.0)
                dead = fl.get("dead", "0/0").split("/")
                paired.append((t - t0, int(fl["loc"]), int(fl["key"]), int(fl["ai"]), x, y, z, int(dead[0]),
                               int(dead[1])))
            elif kind == "NPT":
                npt += 1
    # ownership episodes: owned=1 ... owned=0 (or the trace's end)
    episodes = []
    open_at = {}
    for t, key, owned in ngo:
        if owned == 1:
            open_at[key] = t
        elif key in open_at:
            why = next((w for tt, k, w in nge if k == key and abs(tt - t) < 0.5), 2)
            episodes.append((key, open_at.pop(key), t, why))
    for key, t in open_at.items():
        episodes.append((key, t, t_end - t0, -1))
    episodes.sort(key=lambda e: e[1])
    sent_reports = [r for r in reports if r[1] > 0 or r[2] > 0]
    own_keys = sorted({e[0] for e in episodes})
    paired_keys = sorted({p[1] for p in paired})
    lines = []
    w = lines.append
    w("// Our own NPCs with a job on the guest's game, for tests/npc_hold_test.cpp \"replay\": session A of the 2026-10-20")
    w("// two-PC test (0.16.0), the guest (Bill Nye, -024103.trace). Generated by tools/extract_npc_guest.py from the trace;")
    w("// times in s from the trace's first record (%.4f)." % t0)
    w("//   kGuestOwnEpisodes  NPCs the 0.16 rule made the guest's own (unpaired 5 s): key, owned at, ended at, why")
    w("//                      (GuestNpcEnd: 0 died, 1 handed back, 2 gone (out of his 100 m rounds for 2 s), -1 the")
    w("//                      trace ended first)")
    w("//   kGuestOwnSamples   NO records, 2 Hz while it was his own: t, key, x, y, z, ai, hp, dead")
    w("//   kGuestPaired       NP records of host NPCs with a job paired with one of his own NPCs (no spawned copy):")
    w("//                      t, local id, host key, ai, x, y, z (ours), host dead, our dead")
    w("// %d own-NPC episodes of %d NPC(s) %s; %d NO samples;" % (len(episodes), len(own_keys), own_keys, len(no)))
    w("// %d paired samples of %d local NPC(s) %s." % (len(paired), len(paired_keys), paired_keys))
    w("// What the old rule sent: %d NPT records (states of his own NPCs to the host), NetMonitor reports with" % npt)
    w("// guest-owned messages going out: %d of %d (max %.2f KB/s)." % (
        len(sent_reports), len(reports), max([r[1] for r in reports] or [0])))
    w("#pragma once")
    w("")
    w("static const double kGuestT0 = %.4f;   // s, the trace's first record" % t0)
    w("static const double kGuestEnd = %.4f;  // s from kGuestT0: the trace's last record (the session ended)" % (t_end - t0))
    w("static const int kGuestOldNpt = %d;        // NPT records: own NPC states the 0.16 rule sent" % npt)
    w("static const int kGuestOldSentReports = %d; // NetMonitor reports with guest-owned messages going out" % len(sent_reports))
    w("struct GuestOwnEpisode { unsigned key; double ownedAt, endedAt; int why; };")
    w("static const GuestOwnEpisode kGuestOwnEpisodes[] = {")
    for key, a, b, why in episodes:
        w("    {%du, %.3f, %.3f, %d}," % (key, a, b, why))
    w("};")
    w("struct GuestOwnSample { double t; unsigned key; float x, y, z; int ai, hp, dead; };")
    w("static const GuestOwnSample kGuestOwnSamples[] = {")
    row = []
    for t, key, x, y, z, ai, hp, dead in no:
        row.append("{%.3f, %du, %.2ff, %.2ff, %.2ff, %d, %d, %d}" % (t, key, x, y, z, ai, hp, dead))
        if len(row) == 2:
            w("    " + ", ".join(row) + ",")
            row = []
    if row:
        w("    " + ", ".join(row) + ",")
    w("};")
    w("struct GuestPairedSample { double t; unsigned id, hostKey; int ai; float x, y, z; int hostDead, ourDead; };")
    w("static const GuestPairedSample kGuestPaired[] = {")
    for t, loc, key, ai, x, y, z, hd, od in paired:
        w("    {%.3f, %du, %du, %d, %.2ff, %.2ff, %.2ff, %d, %d}," % (t, loc, key, ai, x, y, z, hd, od))
    w("};")
    text = "\r\n".join(lines) + "\r\n"
    if out:
        with open(out, "wb") as f:
            f.write(text.encode("utf-8"))
        print("wrote %s: %d episodes, %d own samples, %d paired samples, %d NPT, %d/%d sending reports" % (
            out, len(episodes), len(no), len(paired), npt, len(sent_reports), len(reports)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
