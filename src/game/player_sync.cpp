// ---- wire ----------------------------------------------------------------------------------------------------------
void Write(net::ByteWriter& w, const PlayerState& s, uint32_t timeMs) {
    w.U8(kStateVersion);
    w.U32(timeMs);
    for (float v : s.pos) w.F32(v);
    w.F32(s.head[0]);
    w.F32(s.head[1]);
    for (float v : s.vel) w.F32(v);
    w.U8(s.mode);
    w.U8(s.flags);
    w.U8(s.health);
    w.Str(s.weapon);
    w.U8(s.shots);
    for (float v : s.aim) w.F32(v);
    if (s.flags & kInVehicle) {
        w.Str(s.model);
        w.U8(s.seat);
        w.U8(s.keyOwner);
        w.U32(s.vehId);
        for (float v : s.cpos) w.F32(v);
        for (float v : s.quat) w.F32(v);
        for (float v : s.cvel) w.F32(v);
        w.U8(s.ctlValid ? 1 : 0);
        w.U8(static_cast<uint8_t>(motion::PackSnorm8(s.steer)));
        w.U8(motion::PackUnorm8(s.power));
        w.U8(motion::PackUnorm8(s.brake));
        w.U8(motion::PackUnorm8(s.handbrake));
        w.U8(static_cast<uint8_t>(s.gear));
        car_signals::Write(w, s.signals);  // last: see kStateVersion
    }
    actions::Write(w, s.act);
    actions::WritePose(w, s.pose);
}

// A remote string that becomes one whitespace-separated field of a Lua command line: printable ASCII, no spaces.
// Anything else could split the field or start a new command line (a weapon "x\nH ..." would forge a hit).
bool Token(const std::string& s) {
    for (unsigned char c : s)
        if (c <= 0x20 || c >= 0x7F) return false;
    return true;
}

constexpr float kMaxCoord = 1e6f;  // metres; the map is a few km across
constexpr float kMaxSpeed = 1e3f;  // m/s

bool InRange(const float* v, int n, float lim) {
    for (int i = 0; i < n; ++i)
        if (!(std::fabs(v[i]) <= lim)) return false;
    return true;
}

// ---- sync trace (core/trace.h, docs/sync-trace.md) -------------------------------------------------------------------
// The state fields of a TX / RX record: "p=x,y,z h=hx,hy v=vx,vy,vz m=mode f=flags hp=health sh=shots w=weapon
// act=seq:kind pose=bits:body" (pose: player_actions.h kStealth 1, kCarry 2, kLadder 4; body: the carried body)
// plus, in a car, "car=key mdl=model seat=n cp=x,y,z q=qx,qy,qz,qw cv=x,y,z ctl=valid,steer,power,brake,hb,gear sig=n"
// (sig: the car signals byte, game/car_signals.h; 0 = unknown).
std::string TraceFields(const PlayerState& s) {
    char buf[640];
    int n = std::snprintf(buf, sizeof buf,
                          "p=%.3f,%.3f,%.3f h=%.4f,%.4f v=%.3f,%.3f,%.3f m=%u f=%u hp=%u sh=%u w=%s act=%u:%s "
                          "pose=%u:%u",
                          s.pos[0], s.pos[1], s.pos[2], s.head[0], s.head[1], s.vel[0], s.vel[1], s.vel[2], s.mode,
                          s.flags, s.health, s.shots, s.weapon.empty() ? "-" : s.weapon.c_str(), s.act.seq,
                          actions::Name(s.act.last), s.pose.bits, s.pose.body);
    if ((s.flags & kInVehicle) && n > 0 && n < static_cast<int>(sizeof buf))
        std::snprintf(buf + n, sizeof buf - n,
                      " car=%u:%u mdl=%s seat=%u cp=%.3f,%.3f,%.3f q=%.5f,%.5f,%.5f,%.5f cv=%.3f,%.3f,%.3f "
                      "ctl=%d,%.3f,%.3f,%.3f,%.3f,%d sig=%u",
                      s.keyOwner, s.vehId, s.model.c_str(), s.seat, s.cpos[0], s.cpos[1], s.cpos[2], s.quat[0],
                      s.quat[1], s.quat[2], s.quat[3], s.cvel[0], s.cvel[1], s.cvel[2], s.ctlValid ? 1 : 0, s.steer,
                      s.power, s.brake, s.handbrake, static_cast<int>(s.gear), s.signals);
    return buf;
}

constexpr double kTraceInterval = 1.0 / 60;  // PUP / VEH records per remote player (more often on snaps and pins)

// Appends a formatted command line, or nothing if it did not fit (a cut line would lose its '\n' and merge with the
// next command) or out would grow past cap.
template <class... A>
void AppendLine(std::string& out, size_t cap, const char* fmt, A... args) {
    char buf[1024];
    const int n = std::snprintf(buf, sizeof(buf), fmt, args...);
    if (n <= 0 || static_cast<size_t>(n) >= sizeof(buf) || out.size() + static_cast<size_t>(n) > cap) return;
    out.append(buf, static_cast<size_t>(n));
}

bool Read(net::ByteReader& r, PlayerState& s, uint32_t& timeMs) {
    if (r.U8() != kStateVersion) return false;
    timeMs = r.U32();
    for (float& v : s.pos) v = r.F32();
    s.head[0] = r.F32();
    s.head[1] = r.F32();
    for (float& v : s.vel) v = r.F32();
    s.mode = r.U8();
    s.flags = r.U8();
    s.health = r.U8();
    s.weapon = r.Str(32);
    s.shots = r.U8();
    for (float& v : s.aim) v = r.F32();
    if (s.flags & kInVehicle) {
        s.model = r.Str(48);
        s.seat = r.U8();
        s.keyOwner = r.U8();
        s.vehId = r.U32();
        for (float& v : s.cpos) v = r.F32();
        for (float& v : s.quat) v = r.F32();
        for (float& v : s.cvel) v = r.F32();
        s.ctlValid = (r.U8() & 1) != 0;
        s.steer = motion::UnpackSnorm8(static_cast<int8_t>(r.U8()));
        s.power = motion::UnpackUnorm8(r.U8());
        s.brake = motion::UnpackUnorm8(r.U8());
        s.handbrake = motion::UnpackUnorm8(r.U8());
        s.gear = static_cast<int8_t>(r.U8());
        s.signals = car_signals::Read(r);
    }
    actions::Read(r, s.act);  // optional: a state from a build without the action block has none
    actions::ReadPose(r, s.pose);  // optional too (traversal)
    if (!r.Ok()) return false;
    // Everything below ends up in a Lua command line ("T ..."): one %S+ field per string, and numbers small enough
    // that the line fits its buffer. NaN fails every !(|v| <= lim) check.
    if (!Token(s.weapon) || !InRange(s.pos, 3, kMaxCoord) || !InRange(s.head, 2, 2) || !InRange(s.vel, 3, kMaxSpeed) ||
        !InRange(s.aim, 3, 1.5f))
        return false;
    if ((s.flags & kInVehicle) && (!Token(s.model) || !InRange(s.cpos, 3, kMaxCoord) || !InRange(s.quat, 4, 2) ||
                                   !InRange(s.cvel, 3, kMaxSpeed)))
        return false;
    return true;
}

void OnState(net::PlayerId from, net::ByteReader& r) {
    PlayerState s;
    uint32_t timeMs = 0;
    if (!Read(r, s, timeMs)) return;
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    if (!sh.active || from == sh.localId) return;
    Remote& rem = sh.remotes[from];
    const double now = Now();
    rem.clockMs = rem.haveClock ? rem.clockMs + static_cast<int32_t>(timeMs - rem.lastRawMs) : timeMs;
    rem.lastRawMs = timeMs;
    rem.haveClock = true;
    const double t = static_cast<double>(rem.clockMs) / 1000.0;
    if (!rem.snaps.empty() && t <= rem.snaps.back().t) {  // old or duplicate
        ++rem.dropped;
        core::trace::Line("RXD", "from=%u sT=%u last=%.0f", from, timeMs, rem.snaps.back().t * 1000);
        return;
    }
    rem.playout.Observe(t, now);
    rem.offset = rem.playout.Offset();
    rem.haveOffset = true;
    if (rem.recvCount == 0) MC_LOG_INFO("sync: first state from player %u", from);
    if (core::trace::IsOpen())
        core::trace::Line("RX", "from=%u sT=%u off=%.4f %s", from, timeMs, rem.offset, TraceFields(s).c_str());
    const uint8_t sig = (s.flags & kInVehicle) && s.seat == 0 ? s.signals : 0;
    if (sig != rem.signals) {
        MC_LOG_INFO("sync: player %u's car signals: %s (%s)", from, car_signals::Describe(sig).c_str(),
                    car_signals::Changes(rem.signals, sig).c_str());
        rem.signals = sig;
    }
    rem.snaps.push_back({t, std::move(s)});
    while (rem.snaps.size() > kMaxSnaps) rem.snaps.pop_front();
    rem.lastRecv = now;
    ++rem.recvCount;
    ++rem.rateWindowCount;
    if (now - rem.rateWindowStart >= 2.0) {
        rem.rateHz = static_cast<float>(rem.rateWindowCount / (now - rem.rateWindowStart));
        rem.rateWindowStart = now;
        rem.rateWindowCount = 0;
    }
}

// ---- interpolation (main thread, under the lock) -------------------------------------------------------------------
float Lerp(float a, float b, float t) { return a + (b - a) * t; }

PlayerState Interpolate(const Remote& rem, double now) {
    const double rt = rem.playout.RenderTime(now);
    const auto& sn = rem.snaps;
    if (rt <= sn.front().t) return sn.front().s;
    if (rt >= sn.back().t) {
        PlayerState s = sn.back().s;
        const float dt = static_cast<float>(std::min(rt - sn.back().t, kMaxExtrapolate));
        for (int i = 0; i < 3; ++i) s.pos[i] += s.vel[i] * dt;
        if (s.flags & kInVehicle)
            for (int i = 0; i < 3; ++i) s.cpos[i] += s.cvel[i] * dt;
        return s;
    }
    size_t i = 0;
    while (i + 1 < sn.size() && sn[i + 1].t < rt) ++i;
    const Snap& a = sn[i];
    const Snap& b = sn[i + 1];
    const float t = static_cast<float>((rt - a.t) / std::max(1e-6, b.t - a.t));
    PlayerState s = t < 0.5f ? a.s : b.s;  // discrete fields from the nearer snapshot
    auto jumped = [](const float* p, const float* q) {
        const float dx = p[0] - q[0], dy = p[1] - q[1], dz = p[2] - q[2];
        return dx * dx + dy * dy + dz * dz > kTeleport * kTeleport;
    };
    if (jumped(a.s.pos, b.s.pos)) return s;
    // Positions on the Hermite curve through both states with their velocities (no corner at every state)
    auto hermite = [&](const float* p0, const float* v0, const float* p1, const float* v1, float* out) {
        const net::playout::Vec3 h = net::playout::Hermite({p0[0], p0[1], p0[2]}, {v0[0], v0[1], v0[2]},
                                                           {p1[0], p1[1], p1[2]}, {v1[0], v1[1], v1[2]}, b.t - a.t, t);
        out[0] = h.x;
        out[1] = h.y;
        out[2] = h.z;
    };
    hermite(a.s.pos, a.s.vel, b.s.pos, b.s.vel, s.pos);
    for (int k = 0; k < 3; ++k) s.vel[k] = Lerp(a.s.vel[k], b.s.vel[k], t);
    float hx = Lerp(a.s.head[0], b.s.head[0], t), hy = Lerp(a.s.head[1], b.s.head[1], t);
    const float hl = std::sqrt(hx * hx + hy * hy);
    if (hl > 1e-4f) {
        s.head[0] = hx / hl;
        s.head[1] = hy / hl;
    }
    if ((a.s.flags & kInVehicle) && (b.s.flags & kInVehicle) && a.s.vehId == b.s.vehId &&
        !jumped(a.s.cpos, b.s.cpos)) {
        hermite(a.s.cpos, a.s.cvel, b.s.cpos, b.s.cvel, s.cpos);
        for (int k = 0; k < 3; ++k) s.cvel[k] = Lerp(a.s.cvel[k], b.s.cvel[k], t);
        float dot = 0;
        for (int k = 0; k < 4; ++k) dot += a.s.quat[k] * b.s.quat[k];
        const float sign = dot < 0 ? -1.0f : 1.0f;
        float q[4], len = 0;
        for (int k = 0; k < 4; ++k) {
            q[k] = Lerp(a.s.quat[k], b.s.quat[k] * sign, t);
            len += q[k] * q[k];
        }
        len = std::sqrt(len);
        if (len > 1e-6f)
            for (int k = 0; k < 4; ++k) s.quat[k] = q[k] / len;
        if (a.s.ctlValid && b.s.ctlValid) {
            s.steer = Lerp(a.s.steer, b.s.steer, t);
            s.power = Lerp(a.s.power, b.s.power, t);
            s.brake = Lerp(a.s.brake, b.s.brake, t);
            s.handbrake = Lerp(a.s.handbrake, b.s.handbrake, t);
        }
    }
    return s;
}

// Where the remote player is now: the interpolated state (the playout delay in the past, smooth) moved forward along
// his velocity by that delay, at most kMaxLead metres. Without it a car copy trails its driver by speed x delay.
PlayerState Present(const Remote& rem, double now) {
    PlayerState s = Interpolate(rem, now);
    const float lead = static_cast<float>(std::max(0.0, rem.playout.Delay()));
    auto push = [lead](float* p, const float* v) {
        float d[3], len = 0;
        for (int i = 0; i < 3; ++i) {
            d[i] = v[i] * lead;
            len += d[i] * d[i];
        }
        len = std::sqrt(len);
        const float k = len > kMaxLead ? kMaxLead / len : 1.0f;
        for (int i = 0; i < 3; ++i) p[i] += d[i] * k;
    };
    push(s.pos, s.vel);
    if (s.flags & kInVehicle) push(s.cpos, s.cvel);
    return s;
}

