struct PlayerState {
    float pos[3] = {};
    float head[2] = {0, 1};
    float vel[3] = {};
    uint8_t mode = 0;  // 0 idle, 1 walk, 2 run, 3 sprint
    uint8_t flags = 0;
    uint8_t health = 0;
    std::string weapon;  // "" = none
    uint8_t shots = 0;         // shots fired so far (wraps at 256); a change = new shots
    float aim[3] = {0, 1, 0};  // aim direction (camera), unit vector
    // vehicle (flags & kInVehicle)
    std::string model;
    uint8_t seat = 0;
    uint8_t keyOwner = 0;  // car key = (keyOwner, vehId): the first driver's id and the car's GUID on his game
    uint32_t vehId = 0;
    float cpos[3] = {};
    float quat[4] = {0, 0, 0, 1};
    float cvel[3] = {};
    // the driver's controls (seat 0; ctlValid false when his game could not read them)
    bool ctlValid = false;
    float steer = 0;      // steering wish -1..1 (right positive as the game stores it)
    float power = 0;      // throttle 0..1
    float brake = 0;      // 0..1
    float handbrake = 0;  // 0..1
    int8_t gear = 0;      // GetGear(): < 0 reverse (as far as known)
    // visible one-shot actions (punches, throws ...): counter + latest kind, after everything else (player_actions.h)
    actions::State act;
    actions::Pose pose;   // what he keeps doing: sneaking, carrying a body, on a ladder (after the action block)
    uint8_t signals = 0;  // car_signals bits (kValid unset = his game could not read them; then the copy is left alone)
};

