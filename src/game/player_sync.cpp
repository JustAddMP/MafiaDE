void MainTick(lua_State* L, float dt) {
    // what the render thread received for this system so far is handed to the game now (sync trace LAT)
    latency::Applied(latency::kPlayer);
    latency::Applied(latency::kHit);
    Shared& sh = S();
    std::string cmds;
    bool active;
    {
        std::lock_guard lock(sh.mu);
        active = sh.active;
        ApplyModelGates(sh, Now());
        if (sh.removeAll) {
            cmds += "X\n";
            sh.removeAll = false;
        }
        for (net::PlayerId id : sh.removed) cmds += "R " + std::to_string(id) + "\n";
        sh.removed.clear();
        if (active) {
            const double now = Now();
            cmds += "L " + std::to_string(sh.localId) + (sh.isHost ? " 1" : " 0") + (FriendlyFire() ? " 1\n" : " 0\n");
            cmds += "M " + characters::Resolve(LocalModelSetting(), sh.localId) + "\n";
            // last field: the game-sectors guard is in, so every game's puppets may get the friend brain, which keeps
            // them in car seats (player_sync.lua M.Seat / M.Ally)
            cmds += std::string("G ") + (NameTagsOn() ? "1 " : "0 ") + (MapMarkersOn() ? "1 " : "0 ") +
                    (EnemiesTargetGuests() ? "1 " : "0 ") + (sectors_guard::Active() ? "1\n" : "0\n");
            cmds += sh.inCmds;
            sh.inCmds.clear();
            if (sh.enterPressed && now - sh.enterAt < 0.5) cmds += "E\n";
            sh.enterPressed = false;
            if (sh.aimDown) cmds += "A\n";
            // the other players' names for their map markers (player_sync.lua M.names), once a second
            static double lastNames = -10;
            if (now - lastNames >= 1.0) {
                lastNames = now;
                for (const auto& [id, name] : sh.names)
                    if (id != sh.localId) cmds += mapmark::NameLine(id, name);
            }
            for (const auto& [id, name] : sh.names) {  // in the session but nothing received yet: preload the model
                auto it = sh.remotes.find(id);
                if (id != sh.localId && (it == sh.remotes.end() || it->second.snaps.empty()))
                    cmds += "Q " + std::to_string(id) + " " + ProfileFor(sh, id) + "\n";
            }
            for (auto& [id, rem] : sh.remotes) {
                if (rem.snaps.empty()) continue;
                rem.playout.Update(now);  // the render clock toward its adaptive delay (net/playout.h)
                PlayerState s = Present(rem, now);
                if (peer_pause::Remote(static_cast<uint8_t>(id), now) == peer_pause::Quiet::Paused)
                    Freeze(sh, id, rem, s, now);
                else if (rem.frozen)
                    Unfreeze(id, rem, now);
                motion::LocomotionCommand lc;
                motion::VehicleCommand vc;
                DriveCommands(sh, id, rem, s, dt, now, lc, vc);
                const actions::Tracker::Result act = rem.acts.Update(s.act);
                if (act.play != actions::Action::None) {
                    ++rem.actsPlayed;
                    if (rem.actsPlayed <= 40 || rem.actsPlayed % 100 == 0 || act.missed > 0)
                        MC_LOG_INFO("sync: player %u: %s (action #%u, seq %u%s), his puppet plays it", id,
                                    actions::Name(act.play), rem.actsPlayed, s.act.seq,
                                    act.missed > 0 ? ", earlier ones skipped" : "");
                    core::trace::Line("ACT", "id=%u kind=%s seq=%u missed=%d", id, actions::Name(act.play),
                                      s.act.seq, act.missed);
                }
                AppendTarget(cmds, ProfileFor(sh, id), id, s, lc, vc, act.play);
            }
        }
    }
    // Offline the glue only reports the world state (lobby: in the world or not, which save), four times a second.
    static double lastIdle = 0;
    if (!active && cmds.empty() && !_wasActive) {
        const double t = Now();
        if (t - lastIdle < 0.25) return;
        lastIdle = t;
    }
    _wasActive = active;
    if (_moduleFailed) return;
    if (!_moduleLoaded) {
        if (!LoadModule(L)) {
            _moduleFailed = true;
            return;
        }
        _moduleLoaded = true;
    }

    const int top = lua::GetTop(L);
    lua::GetGlobal(L, "MafiaCoop");
    if (lua::TypeOf(L, -1) != lua::TTable) {
        lua::SetTop(L, top);
        _moduleLoaded = false;  // someone wiped it: reload next tick
        return;
    }
    lua::GetField(L, -1, "Update");
    lua::PushNumber(L, dt);
    lua::PushString(L, cmds);
    std::string err;
    if (!lua::PCall(L, 2, 3, &err)) {
        LuaError(err);
        lua::SetTop(L, top);
        return;
    }
    const char* sample = lua::ToString(L, -3);
    const char* status = lua::ToString(L, -2);
    const char* events = lua::ToString(L, -1);
    PlayerState local;
    LocalExtras extras;
    const bool ok = sample && *sample && ParseSample(sample, local, extras);
    const double now = Now();
    if (ok) {
        UpdateLocalMotion(local, now);
        DetectTraversal(local, extras, now);
    }
    {
        std::lock_guard lock(sh.mu);
        sh.luaStatus = status ? status : "";
        if (events && *events) {
            std::istringstream in(events);
            std::string line;
            while (std::getline(in, line)) {
                if (line.rfind("WS ", 0) == 0) {  // world state, also offline
                    sh.inWorld = line.size() > 3 && line[3] == '1';
                    sh.saveId = line.size() > 5 ? line.substr(5) : std::string();
                    sh.worldAt = now;
                    continue;
                }
                if (!sh.active) continue;
                if (line.rfind("PS ", 0) == 0 || line.rfind("VS ", 0) == 0) {  // where a puppet / car copy is
                    OnReport(sh, line, now);
                } else if (line.rfind("NT ", 0) == 0) {  // name tag of a puppet
                    unsigned id = 0;
                    float x = 0, y = 0, d = 0;
                    if (std::sscanf(line.c_str() + 3, "%u %f %f %f", &id, &x, &y, &d) == 4 && id < net::kMaxPlayers)
                        sh.tags[static_cast<net::PlayerId>(id)] = {x, y, d, now};
                } else if (line.rfind("CP ", 0) == 0)
                    sh.outParked.push_back(line);
                else if (line.rfind("WE ", 0) == 0 && sh.isHost)
                    sh.outEnv.push_back(line);
                else if (line.rfind("HT ", 0) == 0)
                    sh.outHits.push_back(line);
                else if (line.rfind("ML ", 0) == 0) {  // our story Tommy's profile changed
                    const std::string look = line.substr(3);
                    if (characters::SafeProfile(look) && look != sh.localLook) {
                        sh.localLook = look;
                        sh.sendModel = true;
                    }
                }
            }
        }
        if (ok) {
            sh.local = std::move(local);
            sh.localValid = true;
            sh.localAt = now;
        }
    }
    lua::SetTop(L, top);
}

// A new sync trace for this session (render thread, under the lock): docs/sync-trace.md "H".
void OpenTrace(const Shared& sh) {
    const GameInfo& gi = GetGameInfo();
    std::string built = __DATE__ "_" __TIME__;
    std::replace(built.begin(), built.end(), ' ', '_');  // one field
    char header[512];
    std::snprintf(header, sizeof header,
                  "game=%s mod=%s core=%s proto=%u state=%u role=%s local=%u hz=%d interp=%d built=%s", gi.modName,
                  gi.modVersion, kCoreVersion, net::kProtocolVersion, kStateVersion,
                  sh.localId == net::kHostPlayer ? "host" : "guest", sh.localId,
                  static_cast<int>(1.0 / SendInterval() + 0.5), static_cast<int>(InterpDelay() * 1000), built.c_str());
    if (core::trace::Open(header, "")) {
        const std::wstring path = core::trace::Path();
        char narrow[MAX_PATH * 3] = {};
        WideCharToMultiByte(CP_UTF8, 0, path.c_str(), -1, narrow, sizeof narrow, nullptr, nullptr);
        MC_LOG_INFO("sync: trace %s", narrow);
    } else {
        MC_LOG_WARN("sync: no trace file (logs\\trace not writable?)");
    }
}

