void PlayerSync::Attach(net::Session& session) {
    _session = &session;
    session.On(kMsgPlayerState, &OnState);
    session.On(kMsgCarParked, &OnCarParked);
    session.On(kMsgWorldEnv, &OnWorldEnv);
    session.On(kMsgHit, &OnHit);
    session.On(kMsgPlayerModel, &OnPlayerModel);
    session.On(peer_pause::kMsgPeerPaused, &OnPeerPaused);
    peer_pause::ClearRemotes();
    _pause.Reset();
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    sh.active = false;  // becomes active in Tick once the session is
    sh.live.clear();
    sh.gates.clear();
    sh.sendModel = true;
    sh.remotes.clear();
    sh.localId = net::kNoPlayer;
}

void PlayerSync::Detach() {
    if (_session) {
        _session->Off(kMsgPlayerState);
        _session->Off(kMsgCarParked);
        _session->Off(kMsgWorldEnv);
        _session->Off(kMsgHit);
        _session->Off(kMsgPlayerModel);
        _session->Off(peer_pause::kMsgPeerPaused);
    }
    peer_pause::ClearRemotes();
    _pause.Reset();
    _session = nullptr;
    _seenPlayers.clear();
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    if (sh.active || !sh.remotes.empty()) {
        MC_LOG_INFO("sync: session ended, removing %zu puppet(s)", sh.remotes.size());
        sh.removeAll = true;
    }
    sh.active = false;
    sh.remotes.clear();
    sh.names.clear();
    sh.inCmds.clear();
    sh.outParked.clear();
    sh.outEnv.clear();
    sh.outHits.clear();
    sh.models.clear();
    sh.live.clear();
    sh.gates.clear();
    sh.lastWeather.clear();
    sh.tags.clear();
    sh.pupReports.clear();
    sh.carReports.clear();
    if (core::trace::IsOpen()) {
        core::trace::Line("END", "why=session-detached");
        core::trace::Close();
    }
}

void PlayerSync::OnPlayerLeft(net::PlayerId id) {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    sh.remotes.erase(id);
    sh.names.erase(id);
    sh.models.erase(id);
    sh.live.erase(id);
    sh.gates.erase(id);
    sh.tags.erase(id);
    sh.pupReports.erase(id);
    sh.carReports.erase(id);
    sh.removed.push_back(id);
    peer_pause::RemoveRemote(static_cast<uint8_t>(id));
    MC_LOG_INFO("sync: player %u left, removing their puppet", id);
    core::trace::Line("PLX", "id=%u", id);
}

void PlayerSync::Tick(float dt, bool enterDown, bool aimDown) {
    if (!_session) return;
    Shared& sh = S();
    const bool active = _session->IsActive();
    PlayerState local;
    bool send = false;
    double sampleAt = 0;
    std::vector<std::string> parked, env, hits;
    bool sendModel = false;
    std::string modelLook, modelWhy;
    int modelSteps = 0;
    bool pauseInWorld = false;
    const bool enterEdge = enterDown && !_enterWasDown;
    _enterWasDown = enterDown;
    {
        std::lock_guard lock(sh.mu);
        if (enterEdge && active) {
            sh.enterPressed = true;
            sh.enterAt = Now();
        }
        parked.swap(sh.outParked);
        env.swap(sh.outEnv);
        hits.swap(sh.outHits);
        sh.aimDown = aimDown && active;
        if (active != sh.active) {
            sh.active = active;
            sh.localId = _session->LocalId();
            MC_LOG_INFO("sync: %s (local player %u)", active ? "active" : "inactive", sh.localId);
            if (!active) {
                sh.removeAll = true;
                sh.remotes.clear();
                _seenPlayers.clear();  // everyone is new once we are back (they get our PlayerModel again)
                if (_session->IsReconnecting()) {
                    // guest lost the host: the session stays and rejoins; the trace stays open across the gap
                    MC_LOG_INFO("sync: connection to the host lost: puppets removed until we are back");
                    core::trace::Line("RCN", "ev=sync-paused");
                } else if (core::trace::IsOpen()) {
                    core::trace::Line("END", "why=session-inactive");
                    core::trace::Close();
                }
            } else if (core::trace::IsOpen()) {
                core::trace::Line("RCN", "ev=sync-resumed local=%u", sh.localId);  // back after a reconnect
            } else {
                OpenTrace(sh);
            }
        }
        if (active) {
            sh.localId = _session->LocalId();
            sh.isHost = sh.localId == net::kHostPlayer;
            sh.names.clear();
            sh.models.clear();
            std::set<std::pair<net::PlayerId, uint32_t>> seen;
            for (const auto& p : _session->Players()) {
                const bool fresh = !_seenPlayers.count({p.id, p.joinSeq});
                if (fresh)  // new in the session (us too, at the start; or back after a lost connection)
                    core::trace::Line("PL", "id=%u model=%s seq=%u name=%s", p.id, p.model.empty() ? "-" : p.model.c_str(),
                                      p.joinSeq, p.name.c_str());
                if (p.id != sh.localId && fresh) sh.sendModel = true;
                sh.names[p.id] = p.name;
                sh.models[p.id] = p.model;
                seen.insert({p.id, p.joinSeq});
            }
            _seenPlayers.swap(seen);
            const char* why = nullptr;
            const double tnow = Now();
            if (sh.outbox.Due(tnow, sh.inWorld && tnow - sh.worldAt < 2.0, &why)) {  // our pick settled
                sh.sendModel = true;
                modelWhy = why;
                modelSteps = sh.outbox.LastSteps();
            } else if (sh.sendModel && sh.outbox.Pending()) {  // a join / look change sends the pick as it is now
                sh.outbox.SentWithOther();
                modelWhy = "with-join";
                modelSteps = sh.outbox.LastSteps();
            }
            if (sh.sendModel) {  // a player joined, our pick settled, or our story look changed
                sh.sendModel = false;
                sendModel = true;
                const std::string resolved = characters::Resolve(LocalModelSetting(), sh.localId);
                modelLook = resolved == "tommy" ? sh.localLook : resolved;
            }
            for (auto it = sh.remotes.begin(); it != sh.remotes.end();) {
                if (!sh.names.count(it->first)) {  // left without an event we saw
                    sh.removed.push_back(it->first);
                    it = sh.remotes.erase(it);
                } else {
                    ++it;
                }
            }
        }
        pauseInWorld = sh.inWorld;
        // trace: clock and link per remote player, once a second
        static double clockAt = 0;
        if (active && core::trace::IsOpen() && Now() - clockAt >= 1.0) {
            clockAt = Now();
            for (const auto& [id, rem] : sh.remotes) {
                const net::PlayerInfo* pi = _session->FindPlayer(id);
                const double ahead = rem.snaps.empty() ? 0 : (rem.snaps.back().t - (clockAt - rem.offset)) * 1000;
                core::trace::Line("CLK", "id=%u off=%.4f rtt=%.1f hz=%.1f snaps=%zu newest=%.1f recv=%u drop=%u "
                                  "last=%.3f pd=%.1f pdt=%.1f jit=%.1f late=%u sclk=%.1f",
                                  id, rem.offset, pi ? pi->rttMs : -1.0f, rem.rateHz, rem.snaps.size(), ahead,
                                  rem.recvCount, rem.dropped, clockAt - rem.lastRecv, rem.playout.Delay() * 1000,
                                  rem.playout.TargetDelay() * 1000, rem.playout.Lateness() * 1000, rem.playout.Late(),
                                  _session->ClockOffsetS() * 1000);
            }
        }
        // The newest sample goes out in the frame the render thread first sees it (core flushes right after this
        // tick), at most at the state rate (a 10 % slack so a 60 fps game sends every frame at 60 Hz).
        _sendAccum += dt;
        if (active && sh.localValid && sh.localAt != _sentSampleAt && _sendAccum >= SendInterval() * 0.9 &&
            Now() - sh.localAt < 1.0) {
            _sendAccum = 0;
            _sentSampleAt = sh.localAt;
            local = sh.local;
            sampleAt = sh.localAt;
            send = true;
        }
    }
    for (const std::string& line : parked) {
        net::ByteWriter pw(96);
        if (active && WriteParked(pw, line)) {
            _session->Broadcast(kMsgCarParked, pw.Span(), net::Reliability::Reliable);
            MC_LOG_INFO("sync: sent CarParked (%s)", line.c_str() + 3);
        }
    }
    for (const std::string& line : env) {
        net::ByteWriter ew(128);
        if (active && WriteEnv(ew, line)) {
            _session->Broadcast(kMsgWorldEnv, ew.Span(), net::Reliability::Reliable);
            if (++_envSent <= 3 || _envSent % 100 == 0)
                MC_LOG_INFO("sync: sent WorldEnv #%u (%s)", _envSent, line.c_str() + 3);
        }
    }
    for (const std::string& line : hits) {
        net::ByteWriter hw(32);
        net::PlayerId victim = net::kNoPlayer;
        if (active && WriteHit(hw, line, victim) && _session->FindPlayer(victim)) {
            _session->SendTo(victim, kMsgHit, hw.Span(), net::Reliability::Reliable);
            MC_LOG_INFO("sync: sent Hit to player %u (%s)", victim, line.c_str() + 3);
        }
    }
    // Our own pause (game/peer_pause.h): the game's script tick stopped (the pause menu, the CO-OP panel from it, a
    // loading screen) or runs through TickPaused only. Everyone is told, on the change and every 2 s while it lasts.
    if (active) {
        const double pnow = Now();
        const double last = lua::LastTickAt(), normal = lua::LastNormalTickAt();
        const bool wasPaused = _pause.Paused();
        peer_pause::Msg pm;
        if (_pause.Update(pnow, last, normal + 0.05 < last, normal, pauseInWorld, pm)) {
            net::ByteWriter pw(8);
            peer_pause::Write(pw, pm);
            _session->Broadcast(peer_pause::kMsgPeerPaused, pw.Span(), net::Reliability::Reliable);
            ++_pauseMsgs;
            if (!pm.paused) peer_pause::SetLocalResumed(pnow);
            if (pm.paused != wasPaused) {
                if (pm.paused)
                    MC_LOG_INFO("sync: our game is paused (%s): told everyone (PeerPaused); they hold our puppet, our "
                                "car and the copies of what our game runs", peer_pause::ReasonName(pm.reason));
                else
                    MC_LOG_INFO("sync: our game runs again after %.1f s: told everyone (no knock checks for %.1f s, "
                                "here too)", pm.pausedMs / 1000.0, peer_pause::kGrace);
            }
            core::trace::Line("PAU", "id=%u ev=%s reason=%u ms=%u", _session->LocalId(),
                              pm.paused ? (pm.paused != wasPaused ? "local-paused" : "local-repeat") : "local-resumed",
                              static_cast<unsigned>(pm.reason), pm.pausedMs);
        }
    } else if (_pause.Paused()) {
        _pause.Reset();
    }
    if (sendModel && active) {
        const std::string model = LocalModelSetting();
        net::ByteWriter mw(200);
        mw.Str(characters::SafeProfile(model) ? model : std::string());
        mw.Str(modelLook);
        _session->Broadcast(kMsgPlayerModel, mw.Span(), net::Reliability::Reliable);
        if (modelSteps > 0)
            MC_LOG_INFO("sync: sent PlayerModel (model '%s', look '%s'; our pick after %d panel step(s), %s)",
                        model.c_str(), modelLook.c_str(), modelSteps, modelWhy.c_str());
        else
            MC_LOG_INFO("sync: sent PlayerModel (model '%s', look '%s')", model.c_str(), modelLook.c_str());
        core::trace::Line("CHM", "id=%u ev=send model=%s steps=%d why=%s", _session->LocalId(),
                          model.empty() ? "-" : model.c_str(), modelSteps,
                          modelSteps > 0 ? modelWhy.c_str() : "join");
    }
    if (!send) return;
    net::ByteWriter w(128);
    // stamped with the moment it was sampled (not sent): the receiver's timeline is the player's, without our
    // sample -> send wait in it
    const uint32_t sentMs = static_cast<uint32_t>(static_cast<uint64_t>(sampleAt * 1000.0));
    Write(w, local, sentMs);
    if (core::trace::IsOpen()) core::trace::Line("TX", "sT=%u %s", sentMs, TraceFields(local).c_str());
    if (_haveActSeq && local.act.seq != _lastActSeq) {  // a punch / throw ... of ours goes out with this state
        ++_actsSent;
        if (_actsSent <= 40 || _actsSent % 100 == 0)
            MC_LOG_INFO("sync: our %s goes out (action #%u, seq %u)", actions::Name(local.act.last), _actsSent,
                        local.act.seq);
        core::trace::Line("ACS", "sT=%u kind=%s seq=%u", sentMs, actions::Name(local.act.last), local.act.seq);
    }
    _lastActSeq = local.act.seq;
    _haveActSeq = true;
    // TODO(interest): players and their cars are always relevant (Kind::Player/PlayerCar, Critical), so PlayerState
    // stays a plain 20 Hz Broadcast. Phase-4 host-mirrored NPCs/vehicles go through net/interest.h instead: register
    // them with an InterestManager, Tick it here at the send rate, spawn/despawn on Enter/Leave and send each peer
    // its SendList with SendTo (docs/interest.md "Integration").
    _session->Broadcast(kMsgPlayerState, w.Span(), net::Reliability::Unreliable);
    if (++_sent == 1) MC_LOG_INFO("sync: sending local state (%zu bytes)", w.Size());
}

std::string PlayerSync::Model() { return LocalModelSetting(); }

bool PlayerSync::InWorld() {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    return sh.inWorld && Now() - sh.worldAt < 2.0;
}

std::string PlayerSync::SaveId() {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    return Now() - sh.worldAt < 2.0 ? sh.saveId : std::string();
}

std::string PlayerSync::CharacterName(net::PlayerId id) {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    std::string picked;
    if (id == sh.localId || !sh.active) {
        picked = LocalModelSetting();
    } else {
        auto gate = sh.gates.find(id);  // the newest pick (his puppet may still wait for it to settle)
        const Shared::Look* newest = gate != sh.gates.end() ? gate->second.Newest() : nullptr;
        auto live = sh.live.find(id);
        auto hello = sh.models.find(id);
        picked = newest                 ? newest->model
                 : live != sh.live.end() ? live->second.model
                 : hello != sh.models.end() ? hello->second
                                            : std::string();
    }
    if (picked.empty() || (!characters::Find(picked, nullptr, nullptr) && characters::Resolve(picked, id) != picked))
        picked = characters::DefaultModel(id);
    return characters::DisplayName(picked);
}

void PlayerSync::GetTags(std::vector<NameTag>& out) {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    if (!sh.active) return;
    const double now = Now();
    for (const auto& [id, t] : sh.tags) {
        if (now - t.at > 0.25) continue;  // not seen this tick (off screen, hidden, paused, loading)
        auto name = sh.names.find(id);
        if (name == sh.names.end()) continue;
        out.push_back({name->second, t.x, t.y, t.dist});
    }
}

void PlayerSync::SetModel(const std::string& model) {
    if (!core::Config::Get().Set("model", model))
        MC_LOG_WARN("sync: could not save model = %s in the settings file", model.c_str());
    MC_LOG_INFO("sync: our character is now %s (%s)", characters::DisplayName(model).c_str(), model.c_str());
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    // not sent per step: once the pick stays for a second, or when the panel closes (model_change.h Outbox)
    sh.outbox.Picked(Now());
    core::trace::Line("CHM", "id=%u ev=pick model=%s", sh.localId, model.empty() ? "-" : model.c_str());
}

void PlayerSync::PanelShown() {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    sh.outbox.PanelShown(Now());
}

int PlayerSync::Health(net::PlayerId id) {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    if (!sh.active) return -1;
    if (id == sh.localId) return sh.localValid && Now() - sh.localAt < 2.0 ? sh.local.health : -1;
    auto it = sh.remotes.find(id);
    if (it == sh.remotes.end() || it->second.snaps.empty() || Now() - it->second.lastRecv > 3.0) return -1;
    return it->second.snaps.back().s.health;
}

void PlayerSync::GetStatus(std::vector<render::OverlayLine>& out) {
    Shared& sh = S();
    std::lock_guard lock(sh.mu);
    if (!sh.active) return;
    // luaStatus: "<factory>|id:state:dist;..."
    const std::string& ls = sh.luaStatus;  // "<factory>|id:state:dist;...|<cars>"
    const size_t bar = ls.find('|');
    const size_t bar2 = bar == std::string::npos ? std::string::npos : ls.find('|', bar + 1);
    const std::string factory = bar == std::string::npos ? "?" : ls.substr(0, bar);
    const std::string cars = bar2 == std::string::npos ? "0" : ls.substr(bar2 + 1);
    std::map<std::string, std::string> pupState;
    if (bar != std::string::npos) {
        std::istringstream in(ls.substr(bar + 1, bar2 == std::string::npos ? std::string::npos : bar2 - bar - 1));
        std::string item;
        while (std::getline(in, item, ';')) {
            const size_t c = item.find(':');
            if (c != std::string::npos) pupState[item.substr(0, c)] = item.substr(c + 1);
        }
    }
    char buf[200];
    std::snprintf(buf, sizeof(buf), "Sync: %s, puppet factory %s, %s shared car(s)",
                  sh.localValid && Now() - sh.localAt < 1.0 ? "in world" : "no local player", factory.c_str(),
                  cars.c_str());
    out.push_back({buf, 0xFFC8C8C8});
    const double now = Now();
    for (const auto& [id, rem] : sh.remotes) {
        auto nameIt = sh.names.find(id);
        auto st = pupState.find(std::to_string(id));
        const PlayerState* last = rem.snaps.empty() ? nullptr : &rem.snaps.back().s;
        auto live = sh.live.find(id);
        auto hello = sh.models.find(id);
        std::string picked =
            live != sh.live.end() ? live->second.model : hello != sh.models.end() ? hello->second : std::string();
        if (picked.empty() || (!characters::Find(picked, nullptr, nullptr) && characters::Resolve(picked, id) != picked))
            picked = characters::DefaultModel(id);  // unknown alias: he is shown as the default for his id
        const std::string who = characters::DisplayName(picked);
        std::snprintf(buf, sizeof(buf), "  %s (%s): puppet %s, %.0f Hz, last %.1f s ago, health %d%s%s",
                      nameIt != sh.names.end() ? nameIt->second.c_str() : "?", who.c_str(),
                      st != pupState.end() ? st->second.c_str() : "pending", rem.rateHz, now - rem.lastRecv,
                      last ? static_cast<int>(last->health) : -1, last && (last->flags & kCrouch) ? ", crouch" : "",
                      last && (last->flags & kAim) ? ", aim" : "");
        out.push_back({buf, 0xFFC8C8C8});
        static const char* const kGaits[] = {"stand", "walk", "run", "sprint"};
        if (rem.inCar && !rem.vehKey.empty()) {
            std::snprintf(buf, sizeof(buf),
                          "    car %s: %s (pins %d), %.2f m off, %.1f/%.1f m/s, steer %+.2f, power %.2f, brake %.2f%s, "
                          "signals %s",
                          rem.vehKey.c_str(), rem.lastVeh.pinned ? "pinned" : "own physics", rem.veh.Pins(),
                          rem.lastVeh.error, rem.lastVeh.cspeed, rem.lastVeh.tspeed, last ? last->steer : 0.0f,
                          rem.lastVeh.power, last ? last->brake : 0.0f,
                          last && !last->ctlValid ? " (no controls from his game)" : "",
                          car_signals::Describe(last ? last->signals : 0).c_str());
        } else {
            std::snprintf(buf, sizeof(buf),
                          "    on foot: %s x%.2f (walk %.1f, run %.1f, sprint %.1f m/s), %.2f m off, wants %.1f m/s%s",
                          kGaits[static_cast<int>(rem.lastLoco.gait) & 3], rem.lastLoco.speedMult,
                          rem.loco.BaseSpeed(motion::Gait::Walk), rem.loco.BaseSpeed(motion::Gait::Run),
                          rem.loco.BaseSpeed(motion::Gait::Sprint), rem.lastLoco.error, rem.lastLoco.want,
                          rem.lastLoco.carry > 0 ? ", catching up" : "");
        }
        out.push_back({buf, 0xFFA0A0A0});
    }
}

